  let lang = 'en';
  try { lang = localStorage.getItem('ms-lang') === 'zh' ? 'zh' : 'en'; } catch (e) {}

  function apply() {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = DICT[lang][document.body.dataset.i18nTitle || 'title.index'];
    const meta = document.querySelector('meta[name="description"]');
    if (meta && DICT[lang][document.body.dataset.i18nDesc || 'desc.index']) meta.content = DICT[lang][document.body.dataset.i18nDesc || 'desc.index'];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = DICT[lang][el.dataset.i18n];
      if (v != null) el.innerHTML = v;
    });
    document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
  }

  function setLang(l) {
    lang = l;
    try { localStorage.setItem('ms-lang', l); } catch (e) {}
    apply();
  }

  window.I18N = {
    get lang() { return lang; },
    t: k => DICT[lang][k],
    setLang,
  };

  // 右上角切换按钮:显示目标语言(脚本置于 body 末尾,DOM 已就绪,立即执行避免语言闪烁)
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(lang === 'en' ? 'zh' : 'en'));
  });
  const syncBtn = () => document.querySelectorAll('.lang-btn').forEach(b => { b.textContent = lang === 'en' ? '中' : 'EN'; });
  document.addEventListener('i18n:change', syncBtn);
  syncBtn();
  apply();
